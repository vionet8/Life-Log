async def analyze_murmur_response(body: str, persona: str = "nagi") -> str:
    """
    つぶやきを受け取り、ペルソナキャラとして返答する。
    """
    prompt = f"""\
ユーザーがこうつぶやきました：
「{body}」

次の3段階のうちどれかを心の中だけで判断し、それに合った返答を書いてください。
判断結果は絶対に出力しないこと。

【心の中だけで判断】
A: 気づき段階 → 感じた・違和感・何かひっかかる
B: 解釈段階  → なぜか・どういう意味か・原因を考えている
C: 更新段階  → 決めた・変えた・気づきを活かした

【Aと判断したら】
・ユーザーの感覚をそのまま受け取る一言
・「なぜそう感じたのか」への問いかけを1つだけ（答えなくていい雰囲気で）

【Bと判断したら】
・考えていることを受け止める一言
・「それを踏まえて何かしたいことはあるか」への問いかけを1つだけ（軽く）

【Cと判断したら】
・変化・決断を受け止める一言
・その先への前向きな一言（問いかけ不要）

あなたのキャラクターで自然に話しかけてください。
"""

    message = await _client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=200,
        system=_system_murmur(persona),
        messages=[{"role": "user", "content": prompt}],
    )
    return message.content[0].text



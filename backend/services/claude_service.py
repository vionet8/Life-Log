async def generate_profile(
    purpose: str,
    custom_purpose: str | None,
    period_label: str,
    entries: list[dict],
    tasks: list[dict],
    persona: str = "nagi",
) -> str:
    if not entries and not tasks:
        return "まだ記録がありません。つぶやきを続けることで、より精度の高いプロフィールが生成できます！"

    style = _PURPOSE_STYLES.get(purpose, _PURPOSE_STYLE_DEFAULT)
    purpose_label = custom_purpose if custom_purpose else style["label"]
    instruction = style["instruction"]
    if custom_purpose:
        instruction = f"用途：「{custom_purpose}」\nこの用途に最適な形式・文体でプロフィールを生成してください。"

    entry_lines = []
    for e in entries:
        line = f"[{e['created_at'][:10]}] {e['body']}"

async def generate_profile(
    purpose: str,
    custom_purpose: str | None,
    period_label: str,
    entries: list[dict],
    tasks: list[dict],
    persona: str = "nagi",
) -> str:
    if not entries and not tasks:
        return "まだ記録がありません。つぶやきを続けることで、より精度の高いプロフィールが生成できます！"

    style = _PURPOSE_STYLES.get(purpose, _PURPOSE_STYLE_DEFAULT)
    purpose_label = custom_purpose if custom_purpose else style["label"]
    instruction = style["instruction"]
    if custom_purpose:
        instruction = f"用途：「{custom_purpose}」\nこの用途に最適な形式・文体でプロフィールを生成してください。"

    entry_lines = []
    for e in entries:
        line = f"[{e['created_at'][:10]}] {e['body']}"
        meta = []
        if e.get("location"):
            meta.append(f"場所:{e['location']}")
        if e.get("score") is not None:
            meta.append(f"点数:{e['score']}点")
        if meta:
            line += f" ／ {' '.join(meta)}"
        entry_lines.append(line)

    entries_text = "\n".join(entry_lines) if entry_lines else "（記録なし）"
    task_lines = [f"・{t['body']}" for t in tasks] if tasks else ["（タスクなし）"]
    tasks_text = "\n".join(task_lines)

    prompt = f"""\
以下はユーザーの「{period_label}」の記録です。

【つぶやき記録（{len(entries)}件）】
{entries_text}

【現在のタスク一覧】
{tasks_text}

# 生成指示
用途：{purpose_label}

{instruction}

# 共通ルール
- 事実（記録）と推論（解釈）を区別する
- 根拠となるつぶやきを適宜引用する
- LINEのメッセージとして読みやすい改行・空行を使う
- マークダウン記法（**太字**など）は使わない
- 全体で600〜900文字を目安に
"""

    message = await _client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=1200,
        system=_system_review(persona),
        messages=[{"role": "user", "content": prompt}],
    )
    return message.content[0].text

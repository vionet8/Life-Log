# ══════════════════════════════════════════════════════════════════════════════
# 振り返りレポート
# ══════════════════════════════════════════════════════════════════════════════

async def generate_review(
    period_label: str,
    entries: list[dict],
    persona: str = "nagi",
) -> str:
    if not entries:
        return "まだ記録がありません。つぶやきを始めてみましょう！"

    entry_lines = []
    for e in entries:
        line = f"[{e['created_at'][:10]}] {e['body']}"
        meta = []
        if e.get("location"):
            meta.append(f"場所:{e['location']}")
        if e.get("weather"):
            meta.append(f"天気:{e['weather']}")
        if e.get("score") is not None:
            s = f"点数:{e['score']}点"
            if e.get("score_reason"):
                s += f"（{e['score_reason']}）"
            meta.append(s)
        if meta:
            line += f" ／ {' '.join(meta)}"
        entry_lines.append(line)

    entries_text = "\n".join(entry_lines)

    prompt = f"""\
以下は「{period_label}」のつぶやき記録（{len(entries)}件）です。

{entries_text}

# 指示

LINEで送る振り返りレポートを作成してください。

## 形式のルール
- LINEのテキストメッセージとして送るため、見やすい改行・空行を使う
- マークダウン記法（**太字**など）は使わない
- 全体で800〜1000文字を目安に
- 記録が少ない場合（3件以下）はデータ分析を省略し、内容に集中する

## 構成

1. 📝 この期間のまとめ
   印象的なキーワードを3〜5個 ＋ 特に印象的なつぶやきを1〜2件引用

2. 📈 データの傾向（記録が4件以上のときのみ）
   場所・天気・点数の傾向を簡潔に。データがない項目は省略。

3. 🔍 思考のパターン
   「気づき」「解釈」「更新」のどれが多かったかを分析。
   根拠として日付や言葉を必ず引用する。評価せず観察として届ける。

4. 💬 来週への問い（ユウは「問い」、ナギは「気になること」、ミライは「未来への問い」）
   ユーザーが自分に問いかけるとよさそうな問いを1つだけ

最後に「この内容に違和感はありますか？」と一言添えてください。
"""

    message = await _client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=1400,
        system=_system_review(persona),
        messages=[{"role": "user", "content": prompt}],
    )
    return message.content[0].text



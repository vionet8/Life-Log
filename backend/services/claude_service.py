def _format_phrase_bank(persona: str) -> str:
    bank = _MURMUR_REACTION_PHRASES.get(persona, _MURMUR_REACTION_PHRASES["nagi"])
    lines = []
    for category, phrases in bank.items():
        lines.append(f"◆{category}")
        lines.extend(f"・{p}" for p in phrases)
    return "\n".join(lines)


def _format_followup_close_phrases(persona: str) -> str:
    phrases = _FOLLOWUP_CLOSE_PHRASES.get(persona, _FOLLOWUP_CLOSE_PHRASES["nagi"])
    return "\n".join(f"・{p}" for p in phrases)


